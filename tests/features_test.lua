test("minimap skin: square with a border, hidden pieces, wheel zoom, button drawer, reset", function()
	local FK = start()
	-- two addon buttons as LibDBIcon and others make them
	local a = CreateFrame("Button", "LibDBIcon10_Other", Minimap) a:SetSize(31, 31) a:SetPoint("CENTER", Minimap, "CENTER", -70, 0)
	local b = CreateFrame("Button", "SomeMinimapButton", Minimap) b:SetSize(31, 31) b:SetPoint("CENTER", Minimap, "CENTER", 0, -70)
	FK.MinimapSkin.Apply({ shape = "square", border = "metal", hide = { "ring", "calendar", "header" }, drawer = true, scale = 1.2 })
	eq(Minimap:GetMaskTexture(), "Interface\\Buttons\\WHITE8X8")
	eq(GetMinimapShape(), "SQUARE")
	ok(not MinimapCompassTexture:IsShown() and not GameTimeFrame:IsShown() and not MinimapCluster.ZoneTextButton:IsShown())
	GameTimeFrame:Show()
	ok(not GameTimeFrame:IsShown(), "stays hidden when the client shows it again")
	ok(FK.MinimapSkin.border:IsShown())
	eq(MinimapCluster:GetScale(), 1.2)
	H.Wheel(Minimap, 1)
	eq(Minimap:GetZoom(), 1)
	-- the drawer collected both buttons
	local d = FK.MinimapSkin.drawer
	ok(d:IsShown())
	eq(a:GetParent(), d.flyout)
	eq(b:GetParent(), d.flyout)
	H.Click(d)
	ok(d.flyout:IsShown() and a:IsVisible())
	eq(H.LayoutIssues(d.flyout), {})
	-- applying again (e.g. a settings change) does not lose the buttons
	FK.MinimapSkin.Apply({ shape = "round", border = "soft", drawer = true })
	eq(Minimap:GetMaskTexture(), "Interface\\CharacterFrame\\TempPortraitAlphaMask")
	ok(GetMinimapShape == nil)
	ok(GameTimeFrame:IsShown(), "pieces not listed any more are shown again")
	eq(a:GetParent(), d.flyout)
	FK.MinimapSkin.Reset()
	eq(a:GetParent(), Minimap)
	eq(select(4, a:GetPoint(1)), -70, "buttons go back where they were")
	ok(MinimapCompassTexture:IsShown())
	eq(MinimapCluster:GetScale(), 1)
	ok(not d:IsShown())
end)
