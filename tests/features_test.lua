local KIT = ROOT .. "/tests/fixtures/KitTest"
local function start() return H.Start(KIT).FK end

test("secret: readable checks and guarded use", function()
	local FK = start()
	ok(FK.Secret.Readable(1, "a"))
	H.SetCombat(true)
	local hp = UnitHealth("player")
	ok(FK.Secret.Is(hp) and not FK.Secret.Readable(1, hp))
	eq(FK.Secret.Use(hp, function(v) return v > 0 end, "hidden"), "hidden")
	ok(FK.Secret.Is(FK.Secret.Text(hp, "%d hp")), "formatting keeps it secret, and does not raise")
	H.SetCombat(false)
	eq(FK.Secret.Use(UnitHealth("player"), function(v) return v > 0 end), true)
end)

test("combat: queued work runs after combat, keyed calls collapse", function()
	local FK = start()
	local runs = {}
	FK:AfterCombat(function() runs[#runs + 1] = "now" end)
	eq(runs, { "now" })
	H.SetCombat(true)
	FK:AfterCombat(function() runs[#runs + 1] = "a" end)
	FK:AfterCombat(function() runs[#runs + 1] = "k1" end, "k")
	FK:AfterCombat(function() runs[#runs + 1] = "k2" end, "k")
	eq(#runs, 1)
	H.SetCombat(false)
	eq(runs, { "now", "a", "k2" })
end)

