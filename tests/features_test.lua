	ok(not MinimapCompassTexture:IsShown() and not GameTimeFrame:IsShown() and not MinimapCluster.ZoneTextButton:IsShown())
	GameTimeFrame:Show()
	ok(not GameTimeFrame:IsShown(), "stays hidden when the client shows it again")
	ok(FK.MinimapSkin.border:IsShown())
	eq(MinimapCluster:GetScale(), 1.2)
	H.Wheel(Minimap, 1)
	eq(Minimap:GetZoom(), 1)
