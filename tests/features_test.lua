test("movers: unlock shows handles, dragging saves, lock in combat", function()
	local FK = start()
	local db = FK:NewDB("KitTestDB", { profile = { pos = {} } })
	local bar = CreateFrame("Frame", nil, UIParent)
	bar:SetSize(200, 20)
	bar:SetPoint("CENTER")
	local m = FK.Movers.Add(bar, { label = "Bar", saved = { db, "profile.pos.bar" } })
	H.Advance(0)
	ok(not m.handle:IsShown())
	FK.Movers.Unlock()
	ok(m.handle:IsShown())
	H.Drag(m.handle, 50, 40)
	H.run(m.handle, "OnDragStop")
	local p = db.profile.pos.bar
	ok(p and p.point, "position saved")
	H.SetCombat(true)
	ok(not FK.Movers.IsUnlocked(), "entering combat locks")
	H.SetCombat(false)
	-- restored on reload
	local x = p.x
	local ns = H.Reload()
	db = ns.FK:NewDB("KitTestDB", { profile = { pos = {} } })
	H.Advance(0)
	local bar2 = CreateFrame("Frame", nil, UIParent)
	bar2:SetSize(200, 20)
	bar2:SetPoint("CENTER")
	ns.FK.Movers.Add(bar2, { saved = { db, "profile.pos.bar" } })
	eq(select(4, bar2:GetPoint(1)), x)
end)

