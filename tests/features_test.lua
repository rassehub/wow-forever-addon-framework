test("comm: round trip, chunking, rate limit, bad input dropped", function()
	local FK = start()
	local got = {}
	local comm = FK:Comm("FKTest", function(data, sender) got[#got + 1] = { data, sender } end)
	ok(not comm:Send({ 1 }), "no group: nothing to send to")
	H.Receive("FKTest", "S" .. FK.Serialize({ hello = "world" }), "GUILD", "Other-Realm")
	eq(got[1], { { hello = "world" }, "Other-Realm" })
	H.Receive("FKTest", "Sos.exit()", "GUILD", "Other-Realm")
	H.Receive("FKTest", "Xjunk", "GUILD", "Other-Realm")
	eq(#got, 1, "malformed messages are dropped")
	-- a big table goes out in parts, at most 10 at once, and arrives whole
	local big = {}
	for i = 1, 300 do big[i] = "entry " .. i end
	local loop = FK:Comm("FKLoop", function(data) got.big = data end, { self = true })
	ok(loop:Send(big, "GUILD"))
	local sent = #H.sent
	ok(sent == 10, "burst of 10, got " .. sent)
	ok(got.big == nil)
	H.Advance(5)
	eq(got.big, big)
	for _, m in ipairs(H.sent) do ok(#m.msg <= 255) end
	-- own messages are ignored by default
	comm:Send("me", "GUILD")
	H.Advance(1)
	eq(#got, 1)
end)

test("minimap button: placed on the edge, drag moves and saves the angle, hide", function()
	local FK = start()
	local db = FK:NewDB("KitTestDB", { profile = { minimap = {} } })
	local clicked
	local btn = FK.MinimapButton({ icon = 134400, title = "Kit", saved = { db, "profile.minimap" }, onClick = function(_, b) clicked = b end })
	H.Advance(0)
	local mx, my = Minimap:GetCenter()
	local bx, by = btn:GetCenter()
	near(math.sqrt((bx - mx) ^ 2 + (by - my) ^ 2), 80, 1)
	H.Click(btn, "RightButton")
	eq(clicked, "RightButton")
	H.Hover(btn)
	eq(H.TooltipLines(), { "Kit" })
	H.Drag(btn, 0, 300)
	H.Advance(0.1)
	H.run(btn, "OnDragStop")
	local angle = db.profile.minimap.angle
	ok(angle and angle ~= 225, "angle saved: " .. tostring(angle))
	btn:SetHidden(true)
	eq(db.profile.minimap.hide, true)
	FK.Compartment({ text = "Kit", icon = 134400, onClick = function(b) clicked = "compartment " .. b end })
	H.compartment[1].func(nil, { buttonName = "LeftButton" })
	eq(clicked, "compartment LeftButton")
end)

