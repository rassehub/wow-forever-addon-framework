test("comm: round trip, chunking, rate limit, bad input dropped", function()
	local FK = start()
	local got = {}
	local comm = FK:Comm("FKTest", function(data, sender) got[#got + 1] = { data, sender } end)
	ok(not comm:Send({ 1 }), "no group: nothing to send to")
	H.Receive("FKTest", "S" .. FK.Serialize({ hello = "world" }), "GUILD", "Other-Realm")
	eq(got[1], { { hello = "world" }, "Other-Realm" })
	H.Receive("FKTest", "Sos.exit()", "GUILD", "Other-Realm")
	H.Receive("FKTest", "Xjunk", "GUILD", "Other-Realm")
	eq(#got, 1, "malformed messages are dropped")
	-- a big table goes out in parts, at most 10 at once, and arrives whole
	local big = {}
	for i = 1, 300 do big[i] = "entry " .. i end
	local loop = FK:Comm("FKLoop", function(data) got.big = data end, { self = true })
	ok(loop:Send(big, "GUILD"))
	local sent = #H.sent
	ok(sent == 10, "burst of 10, got " .. sent)
	ok(got.big == nil)
	H.Advance(5)
	eq(got.big, big)
	for _, m in ipairs(H.sent) do ok(#m.msg <= 255) end
	-- own messages are ignored by default
	comm:Send("me", "GUILD")
	H.Advance(1)
	eq(#got, 1)
end)

