test("minimap skin: unlock mode moves and resizes with the mouse and reports the layout", function()
	local FK = start()
	local got
	FK.MinimapSkin.Apply({ shape = "rect", width = 300, height = 200, unlock = true, onLayout = function(l) got = l end })
	local h = FK.MinimapSkin.handle
	ok(h:IsShown())
	H.Drag(h, -200, -100)
	ok(got and got.position, "moving reports a position")
	-- resize from the bottom-left corner: the top-right corner stays where it is
	local v = FK.MinimapSkin.view
	local right, top = v:GetRight(), v:GetTop()
	H.Drag(h.grips.BOTTOMLEFT, -60, -40)
	eq(got.width, 360, "free width")
	near(got.height, 240, 300 / 64 + 0.5, "free height (from the band shown, which moves in 1/32 steps)")
	local vw, vh = v:GetSize()
	eq(vw, 360)
	near(vh, 240, 360 / 64, "the band follows in 1/32 steps")
	near(v:GetRight(), right, 0.6, "right edge kept")
	near(v:GetTop(), top, 360 / 64, "top edge kept")
	-- and from the top-right corner: the bottom-left stays
	local left, bottom = v:GetLeft(), v:GetBottom()
	H.Drag(h.grips.TOPRIGHT, 40, 20)
	near(v:GetLeft(), left, 0.6, "left edge kept")
	near(v:GetBottom(), bottom, 360 / 64, "bottom edge kept")
	FK.MinimapSkin.Apply({ shape = "rect", width = 360, height = 240 })
	ok(not h:IsShown(), "locking hides the handles")
end)

