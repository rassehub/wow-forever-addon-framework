-- Tests of the emulator itself, against an addon made of bare primitives.
local PLAIN = ROOT .. "/tests/fixtures/Plain"

test("loads an addon, lays it out and clicks", function()
	local ns = H.Start(PLAIN)
	eq(ns.count:GetText(), "Clicks: 0")
	eq({ ns.frame:GetRect() }, { 533, 284, 300, 200 })
	H.Click(ns.button)
	H.Click(ns.button)
	eq(ns.count:GetText(), "Clicks: 2")
	eq(H.LeakedGlobals("Plain"), {})
	eq(H.LayoutIssues(), {})
end)

test("saved variables survive a reload", function()
	local ns = H.Start(PLAIN)
	H.Click(ns.button)
	ns = H.Reload()
	eq(ns.count:GetText(), "Clicks: 1")
	eq(PlainDB.clicks, 1)
end)

test("slash command and Escape toggle the window", function()
	local ns = H.Start(PLAIN)
	H.Slash("/plain")
	ok(not ns.frame:IsShown())
	H.Slash("/plain")
	ok(ns.frame:IsShown())
	H.Key("ESCAPE")
	ok(not ns.frame:IsShown())
end)

test("dragging moves a window and leaves a screen-relative anchor", function()
	local ns = H.Start(PLAIN)
	H.Drag(ns.frame, 100, -50)
	local point, relativeTo, _, x, y = ns.frame:GetPoint()
	eq({ point, relativeTo, x, y }, { "TOPLEFT", nil, 633, -334 })
end)

test("a click on a covered button is refused", function()
	local ns = H.Start(PLAIN)
	local cover = CreateFrame("Frame", nil, ns.frame)
	cover:SetAllPoints()
	cover:EnableMouse(true)
	cover:SetFrameLevel(50)
	raises(function() H.Click(ns.button) end, "covered by")
end)

test("layout: two-point anchors, scale and text measurement", function()
	local f = CreateFrame("Frame", nil, UIParent)
	f:SetPoint("TOPLEFT", 100, -100)
	f:SetPoint("BOTTOMRIGHT", UIParent, "TOPLEFT", 300, -250)
	eq({ f:GetSize() }, { 200, 150 })
	local child = CreateFrame("Frame", nil, f)
	child:SetScale(2)
	child:SetSize(10, 10)
	child:SetPoint("TOPLEFT", 5, -5)
	eq({ H.resolve(child) }, { 110, 768 - 100 - 10 - 20, 20, 20 })
	local fs = f:CreateFontString(nil, "OVERLAY", "GameFontNormal")
	fs:SetPoint("TOPLEFT")
	fs:SetText("|cffff0000Hello|r")
	ok(fs:GetStringWidth() > 20 and fs:GetStringWidth() < 40)
	fs:SetWidth(20)
	fs:SetText("several words that wrap")
	ok(fs:GetNumLines() > 1)
end)

test("layout issues: overflowing text, overlapping controls, unanchored regions", function()
	local f = CreateFrame("Frame", nil, UIParent)
	f:SetSize(60, 20)
	f:SetPoint("TOPLEFT", 1300, -10)
	local fs = f:CreateFontString(nil, "OVERLAY", "GameFontNormal")
	fs:SetPoint("LEFT")
	fs:SetText("This label is far wider than its sixty pixel frame")
	local a, b = CreateFrame("Button", nil, f), CreateFrame("Button", nil, f)
	a:SetSize(40, 20) a:SetPoint("LEFT")
	b:SetSize(40, 20) b:SetPoint("LEFT", 10, 0)
	f:CreateTexture()
	local issues = table.concat(H.LayoutIssues(), "\n")
	ok(issues:find("text overflows its container"), issues)
	ok(issues:find("controls overlap"), issues)
	ok(issues:find("unanchored region"), issues)
end)

test("timers, tickers and OnUpdate run on the virtual clock", function()
	local fired, ticks, updates = false, 0, 0
	C_Timer.After(1, function() fired = true end)
	local ticker = C_Timer.NewTicker(0.5, function() ticks = ticks + 1 end)
	local f = CreateFrame("Frame")
	f:SetScript("OnUpdate", function() updates = updates + 1 end)
	H.Advance(0.9)
	ok(not fired)
	H.Advance(0.2)
	ok(fired)
	eq(ticks, 2)
	ticker:Cancel()
	H.Advance(2)
	eq(ticks, 2)
	ok(updates > 20)
end)

test("edit boxes: focus, typing, numeric filter, enter", function()
	local box = CreateFrame("EditBox", nil, UIParent)
	box:SetSize(100, 20)
	box:SetPoint("CENTER")
	box:SetNumeric(true)
	local entered
	box:SetScript("OnEnterPressed", function(self) entered = self:GetNumber() end)
	H.Click(box)
	H.Type("4a2")
	H.Key("ENTER")
	eq(entered, 42)
end)

test("sliders clamp, snap on drag and report user input", function()
	local s = CreateFrame("Slider", nil, UIParent)
	s:SetSize(200, 16)
	s:SetPoint("CENTER")
	s:SetMinMaxValues(20, 80)
	s:SetValueStep(5)
	s:SetObeyStepOnDrag(true)
	local seen = {}
	s:SetScript("OnValueChanged", function(_, v, user) seen[#seen + 1] = { v, user } end)
	s:SetValue(200)
	H.Slide(s, 43)
	eq(seen, { { 80, false }, { 45, true } })
end)

test("secret values: display is allowed, computing is not", function()
	H.SetCombat(true)
	local hp = UnitHealth("player")
	ok(issecretvalue(hp))
	raises(function() return hp + 1 end, "secret value")
	raises(function() return hp < 10 end, "compare") -- Lua's own message when the other side is a plain number
	local f = CreateFrame("Frame", nil, UIParent)
	local fs = f:CreateFontString(nil, "OVERLAY", "GameFontNormal")
	fs:SetText("HP " .. hp)
	ok(issecretvalue(fs:GetText()), "a font string that was given a secret returns secrets")
	local bar = CreateFrame("StatusBar", nil, UIParent)
	bar:SetMinMaxValues(0, UnitHealthMax("player"))
	bar:SetValue(hp)
	ok(issecretvalue(bar:GetValue()))
	H.SetCombat(false)
	eq(UnitHealth("player"), 3000)
end)

test("client rules are enforced: unknown scripts, templates, namespaces, anchor cycles", function()
	local f = CreateFrame("Frame", nil, UIParent)
	raises(function() f:SetScript("OnClick", function() end) end, 'doesn\'t have a "OnClick" script')
	raises(function() CreateFrame("Button", nil, UIParent, "UIPanelButtonTemplate") end, "not emulated")
	raises(function() C_Item.GetItemSpell(1) end, "C_Item.GetItemSpell is not emulated")
	raises(function() f:SetBackdrop({}) end)
	local a, b = CreateFrame("Frame"), CreateFrame("Frame")
	a:SetPoint("LEFT", b, "RIGHT")
	b:SetPoint("LEFT", a, "RIGHT")
	raises(function() a:GetLeft() end, "anchor cycle")
	ok(os == nil and io == nil and require == nil, "the client has no os/io/require")
end)

test("items load asynchronously", function()
	H.fixtures.items[765] = { name = "Silverleaf", quality = 1, icon = 1, uncached = true }
	eq(C_Item.GetItemInfo(765), nil)
	local name
	Item:CreateFromItemID(765):ContinueOnItemLoad(function() name = C_Item.GetItemInfo(765) end)
	eq(name, nil)
	H.Advance(0.2)
	eq(name, "Silverleaf")
	H.fixtures.items[765] = nil
end)

